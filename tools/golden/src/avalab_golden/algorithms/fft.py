"""Golden cases for the iterative radix-2 Cooley-Tukey FFT and its inverse.

Formula (forward, SciPy convention)::

    X[k] = sum_{n=0}^{N-1} x[n] * exp(-j*2*pi*k*n/N)

Inverse::

    x[n] = (1/N) * sum_{k=0}^{N-1} X[k] * exp(+j*2*pi*k*n/N)

Reference values come from ``scipy.fft.fft`` and ``scipy.fft.ifft`` (float64).
Each case stores the forward spectrum as ``expected.re`` / ``expected.im`` and
``expected.ifft`` = ``scipy.fft.ifft(X).real``, so the TypeScript inverse is
pinned directly, not only through a round trip.

The random case stores the samples generated by
``np.random.default_rng(42).standard_normal(N)``; the TypeScript side consumes
the stored values and never reproduces the RNG. The sine case uses a cosine at
bin 64 of N = 1024 (an exact bin multiple, so there is no spectral leakage).

Complexity of the TypeScript implementation: O(N log N). Edge cases covered:
N = 2, N = 1024, a full-scale impulse, a pure bin-centered cosine, and seeded
Gaussian noise (non-symmetric spectrum values).
"""

from __future__ import annotations

import numpy as np
from scipy import fft as scipy_fft

from avalab_golden.fixtures import GoldenCase

FFT_RTOL = 1e-9
FFT_ATOL = 1e-12
RANDOM_SEED = 42
SIZE = 1024
COSINE_BIN = 64


def _spectrum_case(name: str, samples: np.ndarray) -> GoldenCase:
    spectrum = scipy_fft.fft(samples)
    inverse = scipy_fft.ifft(spectrum).real
    return GoldenCase(
        name=name,
        samples=samples.tolist(),
        sample_rate_hz=None,
        expected={
            "re": spectrum.real.tolist(),
            "im": spectrum.imag.tolist(),
            "ifft": inverse.tolist(),
        },
        rtol=FFT_RTOL,
        atol=FFT_ATOL,
    )


def _n2() -> GoldenCase:
    return _spectrum_case("n2_pair", np.array([0.5, -0.25], dtype=np.float64))


def _random_n1024() -> GoldenCase:
    rng = np.random.default_rng(RANDOM_SEED)
    samples = rng.standard_normal(SIZE)
    return _spectrum_case("random_n1024_seed42", samples)


def _cosine_bin64_n1024() -> GoldenCase:
    sample_index = np.arange(SIZE, dtype=np.float64)
    samples = np.cos(2.0 * np.pi * COSINE_BIN * sample_index / SIZE)
    return _spectrum_case("cosine_bin64_n1024", samples)


def _impulse_n1024() -> GoldenCase:
    samples = np.zeros(SIZE, dtype=np.float64)
    samples[0] = 1.0
    return _spectrum_case("impulse_n1024", samples)


def cases() -> list[GoldenCase]:
    """Return the FFT fixture case set in stable order."""
    return [
        _n2(),
        _random_n1024(),
        _cosine_bin64_n1024(),
        _impulse_n1024(),
    ]
