/**
 * Spectrogram painter (F02, Wave-2 Plan 03 Task 3) — pure dB-chunk → canvas
 * pixels. Chunks arrive frame-major from the worker (frame f holds the
 * `binCount` one-sided bins); this module owns ALL display-axis mapping and
 * the global frame → x mapping, so the view only forwards chunks:
 *
 *   linear: y = H−1 − (row/(rows−1))·(H−1)
 *   log:    f(row) = row/(rows−1)·nyquistHz
 *           y = H−1 − ln(max(f, f_min)/f_min) / ln(nyquistHz/f_min)·(H−1)
 *           with f_min = nyquistHz / rows (the first non-DC bin width), so
 *           row 0 still paints at the bottom and row rows−1 at the top and
 *           the mapping is monotonic. Log tick values are powers of ten
 *           (genuine 10^n ticks), generated by `spectrogramFrequencyTicks`.
 *
 * dB mapping is honest and fixed:
 *   unit = clamp((db − dbMinDb) / (dbMaxDb − dbMinDb), 0, 1)
 * with `dbMaxDb` fixed at 0 dB by the view (the DSP normalizes a full-scale
 * tone to 0 dB), NaN/non-finite dB values map to the floor colour. Colormap
 * LUTs are hardcoded here (no d3); viridis and the cividis-like
 * colorblind-safe ramp are selectable, and the legend prints both dB ends so
 * information is never colour-only.
 *
 * Reference: matplotlib viridis/cividis colormap control points (public
 * domain, embedded as a 10-stop LUT); Smith & van der Walt, "A better
 * default colormap for matplotlib" (2015) for the perceptual ordering.
 *
 * Progressive painting: each chunk repaints only its own device-x band
 * (`putImageData` with a dx offset), so earlier chunks stay on screen. The
 * band edges sit half a decimation stride past the chunk's outermost frames,
 * so adjacent chunks meet with the nearest sampled frame and no stripes
 * appear when `frameStride > 1`. The view clears the canvas when a job starts.
 *
 * Complexity: O(bandWidth·H) time and O(bandWidth·H) space per chunk.
 *
 * Edge cases: binCount < 2, frameCount < 1, frameStride < 1, totalFrames < 1,
 * non-positive width/height or nyquistHz, or a dB map shorter than
 * frameCount·binCount → `RangeError`; NaN/±Infinity dB values are safe (floor
 * colour); device width/height are rounded up to at least one pixel; inputs
 * are never mutated.
 */

export type SpectrogramColormapName = "viridis" | "gray" | "viridisCB";

export type SpectrogramAxisMode = "linear" | "log";

export type Rgb = readonly [red: number, green: number, blue: number];

