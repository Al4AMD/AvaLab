/** Exposed for the legend gradient (same LUT the pixels use). */
export function spectrogramColormapStops(colormap: SpectrogramColormapName): readonly Rgb[] {
  const stops = COLORMAP_STOPS[colormap];
  if (stops === undefined) {
    throw new RangeError(`paintSpectrogram: unknown colormap ${String(colormap)}`);
  }
  return stops;
}

/** CSS gradient string for the colormap legend. */
export function colormapGradientCss(colormap: SpectrogramColormapName): string {
  const stops = spectrogramColormapStops(colormap);
  const last = stops.length - 1;
  const parts = stops.map((color, index) => {
    const position = last === 0 ? 0 : (index / last) * 100;
    return `rgb(${color[0]}, ${color[1]}, ${color[2]}) ${position.toFixed(1)}%`;
  });
  return `linear-gradient(to right, ${parts.join(", ")})`;
}

function clampUnit(value: number): number {
  if (!Number.isFinite(value)) {
    return 0;
  }
  if (value <= 0) {
    return 0;
  }
  if (value >= 1) {
    return 1;
  }
  return value;
}

/** Clamp a dB value into [0,1] across [dbMinDb, dbMaxDb]; NaN-safe. */
export function dbToUnit(db: number, dbMinDb: number, dbMaxDb: number): number {
  if (!Number.isFinite(dbMinDb) || !Number.isFinite(dbMaxDb) || dbMaxDb <= dbMinDb) {
    throw new RangeError(
      `paintSpectrogram: dB range must be finite with max > min (got ${dbMinDb}, ${dbMaxDb})`,
    );
  }
  if (!Number.isFinite(db)) {
    return 0;
  }
  return clampUnit((db - dbMinDb) / (dbMaxDb - dbMinDb));
}

/** Linear interpolation across the hardcoded LUT; unit is clamped. */
const LUT_SIZE = 256;
const lutCache = new Map<SpectrogramColormapName, Uint8Array>();

/** 256-entry packed RGB LUT, built once per colormap (no per-paint alloc). */
function colormapLut(colormap: SpectrogramColormapName): Uint8Array {
  const cached = lutCache.get(colormap);
  if (cached !== undefined) {
    return cached;
  }
  const lut = new Uint8Array(LUT_SIZE * 3);
  for (let index = 0; index < LUT_SIZE; index += 1) {
    const [red, green, blue] = colormapColor(colormap, index / (LUT_SIZE - 1));
    lut[index * 3] = red;
    lut[index * 3 + 1] = green;
    lut[index * 3 + 2] = blue;
  }
  lutCache.set(colormap, lut);
  return lut;
}

export function colormapColor(colormap: SpectrogramColormapName, unit: number): Rgb {
  const stops = spectrogramColormapStops(colormap);
  const clamped = clampUnit(unit);
  const segmentCount = stops.length - 1;
  if (segmentCount <= 0) {
    return stops[0] ?? [0, 0, 0];
  }
  const position = clamped * segmentCount;
  const index = Math.min(segmentCount - 1, Math.floor(position));
  const fraction = position - index;
  const low = stops[index] ?? [0, 0, 0];
  const high = stops[index + 1] ?? low;
  return [
    Math.round(low[0] + (high[0] - low[0]) * fraction),
    Math.round(low[1] + (high[1] - low[1]) * fraction),
    Math.round(low[2] + (high[2] - low[2]) * fraction),
  ];
}

type AxisGeometry = {
  readonly rowCount: number;
  readonly heightPx: number;
  readonly axisMode: SpectrogramAxisMode;
  readonly nyquistHz: number;
};

function assertAxisGeometry(geometry: AxisGeometry): void {
  if (!Number.isInteger(geometry.rowCount) || geometry.rowCount < 2) {
    throw new RangeError(`paintSpectrogram: rowCount must be an integer >= 2`);
  }
  if (!Number.isFinite(geometry.heightPx) || geometry.heightPx < 1) {
    throw new RangeError(`paintSpectrogram: heightPx must be >= 1`);
  }
  if (!Number.isFinite(geometry.nyquistHz) || geometry.nyquistHz <= 0) {
    throw new RangeError(`paintSpectrogram: nyquistHz must be > 0`);
  }
  if (geometry.axisMode !== "linear" && geometry.axisMode !== "log") {
    throw new RangeError(`paintSpectrogram: unknown axisMode ${String(geometry.axisMode)}`);
  }
}

/** Frequency of an FFT row (row 0 = 0 Hz, last row = Nyquist). */
export function rowFrequencyHz(rowIndex: number, rowCount: number, nyquistHz: number): number {
  if (!Number.isInteger(rowCount) || rowCount < 2) {
    throw new RangeError("rowFrequencyHz: rowCount must be an integer >= 2");
  }
  if (!Number.isFinite(nyquistHz) || nyquistHz <= 0) {
    throw new RangeError("rowFrequencyHz: nyquistHz must be > 0");
  }
  const clampedRow = Math.min(Math.max(rowIndex, 0), rowCount - 1);
  return (clampedRow / (rowCount - 1)) * nyquistHz;
}

/**
 * Y device position for a row index (bottom-up frequency, top-down canvas).
 * Monotonic: row 0 -> heightPx−1, last row -> 0, in both axis modes.
 */
export function rowIndexToY(rowIndex: number, geometry: AxisGeometry): number {
  assertAxisGeometry(geometry);
  const maxRow = geometry.rowCount - 1;
  const clampedRow = Math.min(Math.max(rowIndex, 0), maxRow);
  const height = geometry.heightPx - 1;
  if (geometry.axisMode === "linear") {
    return height - (clampedRow / maxRow) * height;
  }
  const minHz = geometry.nyquistHz / geometry.rowCount;
  const frequency = (clampedRow / maxRow) * geometry.nyquistHz;
  const fraction =
    Math.log(Math.max(frequency, minHz) / minHz) / Math.log(geometry.nyquistHz / minHz);
  return height - clampUnit(fraction) * height;
}

/** Inverse of the display mapping (used to sample source rows per pixel). */
export function yToRowIndex(y: number, geometry: AxisGeometry): number {
  assertAxisGeometry(geometry);
  const height = geometry.heightPx - 1;
  const topDown = height <= 0 ? 0 : Math.min(Math.max(y, 0), height);
  const fractionFromBottom = 1 - topDown / height;
  const maxRow = geometry.rowCount - 1;
  if (geometry.axisMode === "linear") {
    return fractionFromBottom * maxRow;
  }
  const minHz = geometry.nyquistHz / geometry.rowCount;
  const frequency = minHz * (geometry.nyquistHz / minHz) ** fractionFromBottom;
  // Row 0 has no finite log frequency; the forward mapping clamps it to the
  // first bin width, so the inverse maps everything at/below that back to 0.
  if (frequency <= minHz * (1 + 1e-12)) {
    return 0;
  }
  return (frequency / geometry.nyquistHz) * maxRow;
}

/** Y device position for an absolute frequency (plot ticks / labels). */
export function frequencyToY(frequencyHz: number, geometry: AxisGeometry): number {
  assertAxisGeometry(geometry);
  if (!Number.isFinite(frequencyHz)) {
    throw new RangeError("frequencyToY: frequencyHz must be finite");
  }
  if (geometry.axisMode === "linear") {
    return geometry.heightPx - 1 - (frequencyHz / geometry.nyquistHz) * (geometry.heightPx - 1);
  }
  const minHz = geometry.nyquistHz / geometry.rowCount;
  const fraction =
    Math.log(Math.max(frequencyHz, minHz) / minHz) / Math.log(geometry.nyquistHz / minHz);
  return geometry.heightPx - 1 - clampUnit(fraction) * (geometry.heightPx - 1);
}

/**
 * Axis tick frequencies: evenly spaced (0, ¼, ½, ¾, Nyquist) on a linear
 * axis; powers of ten inside (f_min, nyquist) on a log axis.
 */
export function spectrogramFrequencyTicks(geometry: AxisGeometry): number[] {
  assertAxisGeometry(geometry);
  if (geometry.axisMode === "linear") {
    return [0, 0.25, 0.5, 0.75, 1].map((fraction) => fraction * geometry.nyquistHz);
  }
  const minHz = geometry.nyquistHz / geometry.rowCount;
  const ticks: number[] = [];
  let decade = 10 ** Math.ceil(Math.log10(minHz));
  while (decade < geometry.nyquistHz) {
    ticks.push(decade);
    decade *= 10;
  }
  return ticks;
}

/** Structural canvas seam: real CanvasRenderingContext2D or a test fake. */
export type SpectrogramPixels = {
  readonly data: Uint8ClampedArray;
  readonly width: number;
  readonly height: number;
};

export type SpectrogramPaintContext = {
  createImageData(width: number, height: number): SpectrogramPixels;
  putImageData(image: SpectrogramPixels, dx: number, dy: number): void;
};

export type SpectrogramChunkPaintOptions = {
  readonly widthPx: number;
  readonly heightPx: number;
  readonly dpr: number;
  /** One-sided frequency bins per frame (rowCount in the DSP result). */
  readonly binCount: number;
  /** Global index of the chunk's first analysed frame. */
  readonly frameStart: number;
  /** Analysed frames in this chunk. */
  readonly frameCount: number;
  /** Every `frameStride`-th frame was analysed (column decimation). */
  readonly frameStride: number;
  /** Global analysed-frame count for the whole source. */
  readonly totalFrames: number;
  readonly dbMinDb: number;
  readonly dbMaxDb: number;
  readonly axisMode: SpectrogramAxisMode;
  readonly nyquistHz: number;
  readonly colormap: SpectrogramColormapName;
};

const MAX_DEVICE_PIXEL_RATIO = 2;

/** Device-x band a chunk owns (inclusive), from its global frame extent. */
export function chunkPixelBand(options: SpectrogramChunkPaintOptions): {
  readonly startPx: number;
  readonly endPx: number;
} {
  const dpr = Math.min(Math.max(options.dpr || 1, 1), MAX_DEVICE_PIXEL_RATIO);
  const width = Math.max(1, Math.round(options.widthPx * dpr));
  const lastFrame = Math.max(0, options.totalFrames - 1);
  const halfStride = options.frameStride / 2;
  const firstFrame = options.frameStart - halfStride;
  const lastChunkFrame =
    options.frameStart + (options.frameCount - 1) * options.frameStride + halfStride;
  const toPx = (frame: number): number =>
    lastFrame === 0 ? 0 : Math.round((frame / lastFrame) * (width - 1));
  const startPx = Math.max(0, toPx(firstFrame));
  const endPx = Math.min(width - 1, toPx(lastChunkFrame));
  return { startPx, endPx };
}

/**
 * Paint one frame-major dB chunk into its device-x band. `dbMap` is
 * `frameCount·binCount` values, frame-major. Nearest-frame sampling fills
 * every band pixel; the y mapping matches the axis helpers above.
 */
export function paintSpectrogramChunk(
  ctx: SpectrogramPaintContext,
  dbMap: Float32Array,
  options: SpectrogramChunkPaintOptions,
): void {
  if (!Number.isInteger(options.binCount) || options.binCount < 2) {
    throw new RangeError("paintSpectrogramChunk: binCount must be an integer >= 2");
  }
  if (!Number.isInteger(options.frameCount) || options.frameCount < 1) {
    throw new RangeError("paintSpectrogramChunk: frameCount must be a positive integer");
  }
  if (!Number.isInteger(options.frameStride) || options.frameStride < 1) {
    throw new RangeError("paintSpectrogramChunk: frameStride must be an integer >= 1");
  }
  if (!Number.isInteger(options.totalFrames) || options.totalFrames < 1) {
    throw new RangeError("paintSpectrogramChunk: totalFrames must be a positive integer");
  }
  if (!Number.isInteger(options.frameStart) || options.frameStart < 0) {
    throw new RangeError("paintSpectrogramChunk: frameStart must be an integer >= 0");
  }
  if (dbMap.length < options.frameCount * options.binCount) {
    throw new RangeError(
      `paintSpectrogramChunk: dB map has ${dbMap.length} values, need ${options.frameCount * options.binCount}`,
    );
  }
  const geometry: AxisGeometry = {
    rowCount: options.binCount,
    heightPx: options.heightPx,
    axisMode: options.axisMode,
    nyquistHz: options.nyquistHz,
  };
  assertAxisGeometry(geometry);
  const dpr = Math.min(Math.max(options.dpr || 1, 1), MAX_DEVICE_PIXEL_RATIO);
  const width = Math.max(1, Math.round(options.widthPx * dpr));
  const height = Math.max(1, Math.round(options.heightPx * dpr));
  const { startPx, endPx } = chunkPixelBand(options);
  const bandWidth = endPx - startPx + 1;
  const image = ctx.createImageData(bandWidth, height);
  const data = image.data;
  const deviceGeometry: AxisGeometry = { ...geometry, heightPx: height };
  const colorLut = colormapLut(options.colormap);
  const lastFrame = Math.max(0, options.totalFrames - 1);
  const lastSlot = options.frameCount - 1;
  const binCount = options.binCount;

  const rowForY = new Int32Array(height);
  for (let y = 0; y < height; y += 1) {
    const rowFloat = yToRowIndex(y, deviceGeometry);
    rowForY[y] = Math.min(binCount - 1, Math.max(0, Math.round(rowFloat)));
  }

  for (let bandX = 0; bandX < bandWidth; bandX += 1) {
    const x = startPx + bandX;
    const globalFrame = lastFrame === 0 ? 0 : Math.round((x / (width - 1)) * lastFrame);
    const rawSlot = Math.round((globalFrame - options.frameStart) / options.frameStride);
    const slot = Math.min(lastSlot, Math.max(0, rawSlot));
    const frameOffset = slot * binCount;
    for (let y = 0; y < height; y += 1) {
      const db = dbMap[frameOffset + (rowForY[y] ?? 0)] ?? options.dbMinDb;
      const unit = dbToUnit(db, options.dbMinDb, options.dbMaxDb);
      const lutOffset = Math.round(unit * 255) * 3;
      const pixel = (y * bandWidth + bandX) * 4;
      data[pixel] = colorLut[lutOffset] ?? 0;
      data[pixel + 1] = colorLut[lutOffset + 1] ?? 0;
      data[pixel + 2] = colorLut[lutOffset + 2] ?? 0;
      data[pixel + 3] = 255;
    }
  }
  ctx.putImageData(image, startPx, 0);
}
